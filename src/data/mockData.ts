/** daysAgo 天前的 hh:mm */
function d(daysAgo: number, hh = 9, mm = 30): string {
  const t = new Date();
  t.setDate(t.getDate() - daysAgo);
  t.setHours(hh, mm, 0, 0);
  return t.toISOString();
}

